#!/bin/sh
# ============================================================================
#  LINKOA OA - 容器入口脚本
#  main.py 在导入阶段就会挂载 /uploads 静态目录（StaticFiles），
#  若目录不存在会直接抛 RuntimeError 导致容器退出。
#  这里在启动 uvicorn 前确保目录存在（V1.4.18 起本地与 Docker 统一用 data/，容器内即 /app/data）。
# ============================================================================
set -e

mkdir -p /app/data/uploads

exec "$@"
